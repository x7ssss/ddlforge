describe('v0.7.0 Adversarial & Multi-Rule Integration', () => {
  it('detects all 5 v0.7.0 rule violations in a single adversarial ORM migration', () => {
    const sql = `
      -- 1. identity sequence start with 1
      ALTER TABLE users ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1);

      -- 2. attach partition without pre-validated check
      ALTER TABLE measurements ATTACH PARTITION measurements_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

      -- 3. enum recreate + column type rewrite with text cast
      DROP TYPE account_status;
      CREATE TYPE account_status AS ENUM ('active', 'inactive', 'banned');
      ALTER TABLE accounts ALTER COLUMN status TYPE account_status USING status::text::account_status;

      -- 4. non-transactional inside explicit transaction (VACUUM)
      BEGIN;
      VACUUM ANALYZE users;
      COMMIT;

      -- 5. lock accumulation: DDL + DML
      ALTER TABLE orders ADD COLUMN processed BOOLEAN DEFAULT FALSE;
      UPDATE orders SET processed = TRUE WHERE created_at < NOW() - INTERVAL '1 year';
    `;

    const res = analyzeSql(sql);
    const v070RuleIds = new Set([
      'identity-sequence-start-with',
      'attach-partition-missing-check',
      'enum-recreate-table-rewrite',
      'non-transactional-in-transaction',
      'lock-accumulation-mixed-ddl-dml',
    ]);
    const foundRuleIds = new Set(res.findings.map(f => f.ruleId));

    for (const ruleId of v070RuleIds) {
      assert.ok(
        foundRuleIds.has(ruleId),
        `Expected to find rule ${ruleId}, but found: ${[...foundRuleIds].join(', ')}`
      );
    }
  });

  it('produces 0 findings from v0.7.0 rules for a comprehensive safe migration', () => {
    const sql = `
      -- 1. identity: no explicit START WITH (safe)
      ALTER TABLE users ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;

      -- 2. attach partition: with pre-validated check (4-phase pattern)
      ALTER TABLE measurements_2026 ADD CONSTRAINT chk_measurements_bounds
        CHECK (created_at >= '2026-01-01' AND created_at < '2027-01-01') NOT VALID;
      ALTER TABLE measurements_2026 VALIDATE CONSTRAINT chk_measurements_bounds;
      ALTER TABLE measurements ATTACH PARTITION measurements_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

      -- 3. enum label addition (not recreation): safe
      ALTER TYPE account_status ADD VALUE IF NOT EXISTS 'suspended';

      -- 4. concurrent index outside transaction (standalone)
      CREATE INDEX CONCURRENTLY idx_users_score ON users (score);

      -- 5. DDL only, no subsequent DML in same file
      ALTER TABLE orders ADD COLUMN processed BOOLEAN DEFAULT FALSE;
    `;

    const res = analyzeSql(sql, { pgVersion: 16 });
    const v070Findings = res.findings.filter(f =>
      ['identity-sequence-start-with', 'attach-partition-missing-check', 'enum-recreate-table-rewrite',
       'non-transactional-in-transaction', 'lock-accumulation-mixed-ddl-dml'].includes(f.ruleId)
    );
    assert.strictEqual(
      v070Findings.length,
      0,
      `Expected 0 v0.7.0 findings for safe migration, got: ${JSON.stringify(v070Findings)}`
    );
  });

  it('does not false positive on keywords inside comments or dollar-quoted function bodies', () => {
    const sql = `
      CREATE OR REPLACE FUNCTION safe_attach() RETURNS void AS $$
      BEGIN
        -- ATTACH PARTITION is mentioned here in a comment
        -- START WITH 1 is mentioned here in a comment
        -- DROP TYPE and CREATE TYPE as ENUM
        -- UPDATE users SET ... is a comment
        RAISE NOTICE 'doing nothing';
      END;
      $$ LANGUAGE plpgsql;
    `;
    const res = analyzeSql(sql);
    const v070Findings = res.findings.filter(f =>
      ['identity-sequence-start-with', 'attach-partition-missing-check', 'enum-recreate-table-rewrite',
       'non-transactional-in-transaction', 'lock-accumulation-mixed-ddl-dml'].includes(f.ruleId)
    );
    assert.strictEqual(
      v070Findings.length,
      0,
      `Unexpected false positive: ${JSON.stringify(v070Findings)}`
    );
  });

  it('handles lowercase SQL and quoted identifiers correctly', () => {
    const sql = `
      alter table "public"."users"
        alter column "id" add generated always as identity (start with 1);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.strictEqual(res.findings[0].ruleId, 'identity-sequence-start-with');
  });
});
