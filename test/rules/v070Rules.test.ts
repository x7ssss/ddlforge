/* Rule 4: non-transactional-in-transaction                                   */
/* ────────────────────────────────────────────────────────────────────────── */

describe('Rule: non-transactional-in-transaction', () => {
  it('detects REINDEX CONCURRENTLY inside BEGIN...COMMIT as BLOCKER', () => {
    const sql = `
      BEGIN;
      REINDEX TABLE CONCURRENTLY users;
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.strictEqual(f.ruleId, 'non-transactional-in-transaction');
    assert.strictEqual(f.severity, 'BLOCKER');
    assert.ok(f.message.includes('REINDEX CONCURRENTLY'));
    assert.ok(f.message.includes('SQLSTATE 25001'));
    assert.ok(f.detail.includes('transaction block'));
  });

  it('detects VACUUM inside BEGIN...COMMIT as BLOCKER', () => {
    const sql = `
      BEGIN;
      VACUUM ANALYZE users;
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('VACUUM'));
  });

  it('detects ALTER TYPE ... ADD VALUE inside BEGIN...COMMIT as BLOCKER', () => {
    const sql = `
      BEGIN;
      ALTER TYPE user_role ADD VALUE 'superadmin';
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('ALTER TYPE ... ADD VALUE'));
  });

  it('detects REINDEX CONCURRENTLY in START TRANSACTION...END block', () => {
    const sql = `
      START TRANSACTION;
      REINDEX INDEX CONCURRENTLY idx_orders;
      END;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 1);
  });

  it('detects REINDEX CONCURRENTLY in Prisma migration without pragma', () => {
    const sql = `REINDEX TABLE CONCURRENTLY users;`;
    const res = analyzeSql(sql, {
      rules: [nonTransactionalInTransactionRule],
      filePath: 'prisma/migrations/20260918_reindex/migration.sql',
    });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('REINDEX CONCURRENTLY'));
    assert.ok(res.findings[0].message.includes('prisma-migrate-disable-next-transaction'));
  });

  it('passes REINDEX CONCURRENTLY in Prisma migration WITH prisma-migrate-disable-next-transaction', () => {
    const sql = `
      -- prisma-migrate-disable-next-transaction
      REINDEX TABLE CONCURRENTLY users;
    `;
    const res = analyzeSql(sql, {
      rules: [nonTransactionalInTransactionRule],
      filePath: 'prisma/migrations/20260918_reindex/migration.sql',
    });
    assert.strictEqual(res.blockersCount, 0);
    assert.strictEqual(res.findings.length, 0);
  });

  it('passes REINDEX CONCURRENTLY in Prisma migration WITH legacy prisma:no-transaction', () => {
    const sql = `
      -- prisma:no-transaction
      REINDEX TABLE CONCURRENTLY users;
    `;
    const res = analyzeSql(sql, {
      rules: [nonTransactionalInTransactionRule],
      filePath: 'prisma/migrations/20260918_reindex/migration.sql',
    });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('passes VACUUM standalone (no transaction)', () => {
    const sql = `VACUUM ANALYZE users;`;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('passes REINDEX CONCURRENTLY standalone (no transaction)', () => {
    const sql = `REINDEX TABLE CONCURRENTLY users;`;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 0);
    assert.strictEqual(res.findings.length, 0);
  });

  it('passes CREATE INDEX (non-concurrent) inside transaction', () => {
    const sql = `
      BEGIN;
      CREATE INDEX idx_users_email ON users (email);
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('passes when ignored with directive comment', () => {
    const sql = `
      BEGIN;
      -- ddlforge-ignore non-transactional-in-transaction
      VACUUM ANALYZE users;
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.strictEqual(res.findings.length, 0);
  });

  it('detects multiple non-transactional statements inside a single transaction', () => {
    const sql = `
      BEGIN;
      REINDEX TABLE CONCURRENTLY a;
      VACUUM b;
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [nonTransactionalInTransactionRule] });
    assert.ok(res.blockersCount >= 2, `Expected at least 2 blockers, got ${res.blockersCount}`);
  });

  it('detects non-transactional-in-transaction in analyzeSql default rules for REINDEX CONCURRENTLY in tx', () => {
    const sql = `
      BEGIN;
      REINDEX TABLE CONCURRENTLY t;
      COMMIT;
    `;
    const res = analyzeSql(sql);
    // Should fire both concurrent-index-in-transaction and non-transactional-in-transaction
    assert.ok(res.findings.some(f => f.ruleId === 'non-transactional-in-transaction'));
  });
});

/* ────────────────────────────────────────────────────────────────────────── */
/* Rule 5: lock-accumulation-mixed-ddl-dml                                    */
/* ────────────────────────────────────────────────────────────────────────── */

describe('Rule: lock-accumulation-mixed-ddl-dml', () => {
  it('detects ALTER TABLE followed by UPDATE in the same file as BLOCKER', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN last_login TIMESTAMPTZ;
      UPDATE users SET last_login = NOW() WHERE last_login IS NULL;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.strictEqual(f.ruleId, 'lock-accumulation-mixed-ddl-dml');
    assert.strictEqual(f.severity, 'BLOCKER');
    assert.strictEqual(f.lockLevel, PostgresLockLevel.ACCESS_EXCLUSIVE);
    assert.ok(f.message.includes('ALTER TABLE'));
    assert.ok(f.message.includes('UPDATE'));
    assert.ok(f.message.includes('"users"'));
    assert.ok(f.suggestion.includes('Phase 1'));
    assert.ok(f.suggestion.includes('Phase 2'));
  });

  it('detects ALTER TABLE followed by INSERT in the same file as BLOCKER', () => {
    const sql = `
      ALTER TABLE audit_log ADD COLUMN event_type TEXT NOT NULL DEFAULT 'unknown';
      INSERT INTO audit_log (entity_id, event_type) SELECT id, 'migration' FROM entities;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('INSERT'));
    assert.ok(res.findings[0].message.includes('"audit_log"'));
  });

  it('detects ALTER TABLE followed by DELETE in the same file as BLOCKER', () => {
    const sql = `
      ALTER TABLE sessions ADD COLUMN is_valid BOOLEAN DEFAULT TRUE;
      DELETE FROM sessions WHERE created_at < NOW() - INTERVAL '30 days';
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('DELETE'));
    assert.ok(res.findings[0].message.includes('"sessions"'));
  });

  it('detects DDL + DML inside explicit BEGIN...COMMIT block as BLOCKER', () => {
    const sql = `
      BEGIN;
      ALTER TABLE products ADD COLUMN discount_rate NUMERIC(5,2) DEFAULT 0;
      UPDATE products SET discount_rate = 0.1 WHERE category = 'sale';
      COMMIT;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('"products"'));
  });

  it('passes when DML comes BEFORE DDL in same file (no lock accumulation)', () => {
    // DML before DDL: DDL lock is not yet acquired when DML runs
    const sql = `
      UPDATE users SET last_login = NOW() WHERE last_login IS NULL;
      ALTER TABLE users ADD COLUMN last_login TIMESTAMPTZ;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length, 0);
  });

  it('passes pure DDL-only migration (no DML)', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN middle_name TEXT;
      ALTER TABLE users ADD COLUMN nickname TEXT;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length, 0);
  });

  it('passes pure DML-only migration (no DDL)', () => {
    const sql = `
      UPDATE users SET active = true WHERE active IS NULL;
      DELETE FROM sessions WHERE expired_at < NOW();
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length, 0);
  });

  it('passes SELECT statement after ALTER TABLE (reads are not DML lock accumulators)', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN age INT;
      SELECT COUNT(*) FROM users;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length, 0);
  });

  it('detects multiple DDL+DML pairs in the same migration file', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN col1 TEXT;
      UPDATE users SET col1 = 'x';
      ALTER TABLE orders ADD COLUMN col2 TEXT;
      INSERT INTO orders (id) SELECT id FROM old_orders;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    // Should detect at least 2 findings (one per DDL+DML pair)
    assert.ok(
      res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length >= 2,
      `Expected at least 2 findings, got ${res.findings.length}`
    );
  });

  it('passes when ignored with directive comment on the DML statement', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN last_login TIMESTAMPTZ;
      -- ddlforge-ignore lock-accumulation-mixed-ddl-dml
      UPDATE users SET last_login = NOW() WHERE last_login IS NULL;
    `;
    const res = analyzeSql(sql, { rules: [lockAccumulationMixedDdlDmlRule] });
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml').length, 0);
  });

  it('detects lock-accumulation-mixed-ddl-dml in analyzeSql default rules', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN score INT DEFAULT 0;
      UPDATE users SET score = 100 WHERE score = 0;
    `;
    const res = analyzeSql(sql);
    assert.ok(res.findings.some(f => f.ruleId === 'lock-accumulation-mixed-ddl-dml'));
  });
});

