/* ────────────────────────────────────────────────────────────────────────── */
/* Rule 1: identity-sequence-start-with                                       */
/* ────────────────────────────────────────────────────────────────────────── */

describe('Rule: identity-sequence-start-with', () => {
  it('detects ADD GENERATED ALWAYS AS IDENTITY with START WITH 1 as BLOCKER', () => {
    const sql = `
      ALTER TABLE users
        ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.strictEqual(f.ruleId, 'identity-sequence-start-with');
    assert.strictEqual(f.severity, 'BLOCKER');
    assert.strictEqual(f.lockLevel, PostgresLockLevel.ACCESS_EXCLUSIVE);
    assert.ok(f.message.includes('"id"'));
    assert.ok(f.message.includes('"users"'));
    assert.ok(f.message.includes('START'));
    assert.ok(f.suggestion.includes('setval'));
    assert.ok(f.suggestion.includes('pg_get_serial_sequence'));
  });

  it('detects ADD GENERATED BY DEFAULT AS IDENTITY with START WITH 0 as BLOCKER', () => {
    const sql = `
      ALTER TABLE orders
        ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 0);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.ok(f.message.includes('"order_id"'));
    assert.ok(f.message.includes('"orders"'));
    assert.ok(f.message.includes('0'));
  });

  it('detects RESTART WITH 1 on identity column as BLOCKER', () => {
    const sql = `
      ALTER TABLE products
        ALTER COLUMN product_id RESTART WITH 1;
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.ok(f.message.includes('RESTART'));
    assert.ok(f.message.includes('"product_id"'));
  });

  it('passes ADD GENERATED AS IDENTITY without START WITH (safe)', () => {
    const sql = `
      ALTER TABLE users
        ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 0);
    assert.strictEqual(res.findings.length, 0);
  });

  it('passes ADD GENERATED AS IDENTITY with START WITH 1000 (safe - value > 1)', () => {
    const sql = `
      ALTER TABLE users
        ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1000);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 0);
    assert.strictEqual(res.findings.length, 0);
  });

  it('passes ADD GENERATED AS IDENTITY with RESTART WITH 5000 (safe)', () => {
    const sql = `
      ALTER TABLE orders
        ALTER COLUMN order_id RESTART WITH 5000;
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('handles schema-qualified table name in identity restart', () => {
    const sql = `
      ALTER TABLE public.accounts
        ALTER COLUMN account_id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('"public.accounts"'));
  });

  it('does not flag CREATE TABLE with inline GENERATED AS IDENTITY', () => {
    const sql = `
      CREATE TABLE users (
        id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL
      );
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('passes when ignored with directive comment', () => {
    const sql = `
      -- ddlforge-ignore identity-sequence-start-with
      ALTER TABLE users ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1);
    `;
    const res = analyzeSql(sql, { rules: [identitySequenceStartWithRule] });
    assert.strictEqual(res.findings.length, 0);
  });

  it('detects identity-sequence-start-with in analyzeSql default rules', () => {
    const sql = `ALTER TABLE users ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (START WITH 1);`;
    const res = analyzeSql(sql);
    assert.ok(res.findings.some(f => f.ruleId === 'identity-sequence-start-with'));
  });
});

/* ────────────────────────────────────────────────────────────────────────── */
/* Rule 2: attach-partition-missing-check                                     */
/* ────────────────────────────────────────────────────────────────────────── */

describe('Rule: attach-partition-missing-check', () => {
  it('detects bare ATTACH PARTITION without any prior CHECK constraint as BLOCKER', () => {
    const sql = `
      ALTER TABLE measurements
        ATTACH PARTITION measurements_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.strictEqual(f.ruleId, 'attach-partition-missing-check');
    assert.strictEqual(f.severity, 'BLOCKER');
    assert.strictEqual(f.lockLevel, PostgresLockLevel.ACCESS_EXCLUSIVE);
    assert.ok(f.message.includes('"measurements_2026"'));
    assert.ok(f.message.includes('"measurements"'));
    assert.ok(f.suggestion.includes('NOT VALID'));
    assert.ok(f.suggestion.includes('VALIDATE CONSTRAINT'));
  });

  it('passes ATTACH PARTITION when pre-validated CHECK constraint exists', () => {
    const sql = `
      ALTER TABLE measurements_2026 ADD CONSTRAINT chk_bounds
        CHECK (created_at >= '2026-01-01' AND created_at < '2027-01-01') NOT VALID;
      ALTER TABLE measurements_2026 VALIDATE CONSTRAINT chk_bounds;
      ALTER TABLE measurements
        ATTACH PARTITION measurements_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.blockersCount, 0, `Unexpected findings: ${JSON.stringify(res.findings)}`);
    assert.strictEqual(res.findings.length, 0);
  });

  it('detects ATTACH PARTITION with only NOT VALID check but no VALIDATE (incomplete pattern)', () => {
    const sql = `
      ALTER TABLE measurements_2026 ADD CONSTRAINT chk_bounds
        CHECK (created_at >= '2026-01-01') NOT VALID;
      -- Missing: ALTER TABLE measurements_2026 VALIDATE CONSTRAINT chk_bounds;
      ALTER TABLE measurements
        ATTACH PARTITION measurements_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.blockersCount, 1, `Expected blocker for missing VALIDATE: ${JSON.stringify(res.findings)}`);
  });

  it('handles IF EXISTS and ONLY modifiers on the parent table', () => {
    const sql = `
      ALTER TABLE IF EXISTS ONLY logs
        ATTACH PARTITION logs_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('"logs_2026"'));
    assert.ok(res.findings[0].message.includes('"logs"'));
  });

  it('does not flag DETACH PARTITION', () => {
    const sql = `
      ALTER TABLE measurements DETACH PARTITION measurements_2025 CONCURRENTLY;
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.blockersCount, 0);
  });

  it('does not flag other ALTER TABLE operations', () => {
    const sql = `
      ALTER TABLE users ADD COLUMN middle_name TEXT;
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.findings.length, 0);
  });

  it('passes when ignored with directive comment', () => {
    const sql = `
      -- ddlforge-ignore attach-partition-missing-check
      ALTER TABLE measurements ATTACH PARTITION measurements_2026 FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql, { rules: [attachPartitionMissingCheckRule] });
    assert.strictEqual(res.findings.length, 0);
  });

  it('detects attach-partition-missing-check in analyzeSql default rules', () => {
    const sql = `
      ALTER TABLE orders ATTACH PARTITION orders_2026
        FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
    `;
    const res = analyzeSql(sql);
    assert.ok(res.findings.some(f => f.ruleId === 'attach-partition-missing-check'));
  });
});

/* ────────────────────────────────────────────────────────────────────────── */
/* Rule 3: enum-recreate-table-rewrite                                        */
/* ────────────────────────────────────────────────────────────────────────── */

describe('Rule: enum-recreate-table-rewrite', () => {
  it('detects DROP TYPE + CREATE TYPE AS ENUM + ALTER COLUMN TYPE USING ::text cast as BLOCKER', () => {
    const sql = `
      DROP TYPE user_status;
      CREATE TYPE user_status AS ENUM ('active', 'inactive', 'suspended');
      ALTER TABLE users
        ALTER COLUMN status TYPE user_status USING status::text::user_status;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule] });
    assert.strictEqual(res.blockersCount, 1);
    const f = res.findings[0];
    assert.strictEqual(f.ruleId, 'enum-recreate-table-rewrite');
    assert.strictEqual(f.severity, 'BLOCKER');
    assert.strictEqual(f.lockLevel, PostgresLockLevel.ACCESS_EXCLUSIVE);
    assert.ok(f.message.includes('"status"'));
    assert.ok(f.message.includes('"users"'));
    assert.ok(f.detail.includes('user_status'));
  });

  it('detects enum recreate with IF EXISTS DROP TYPE', () => {
    const sql = `
      DROP TYPE IF EXISTS order_state;
      CREATE TYPE order_state AS ENUM ('pending', 'shipped', 'delivered', 'cancelled');
      ALTER TABLE orders
        ALTER COLUMN state TYPE order_state USING state::varchar::order_state;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule] });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].message.includes('"state"'));
    assert.ok(res.findings[0].message.includes('"orders"'));
  });

  it('passes ALTER COLUMN TYPE without enum recreation in the file', () => {
    // No DROP TYPE + CREATE TYPE pair -> no enum recreation -> no flag
    const sql = `
      ALTER TABLE users
        ALTER COLUMN status TYPE text USING status::text;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule] });
    // The enum-recreate rule should not fire since no enum was recreated
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'enum-recreate-table-rewrite').length, 0);
  });

  it('passes DROP TYPE + CREATE TYPE + ALTER COLUMN TYPE without text-cast USING', () => {
    // USING expression doesn't use ::text intermediate cast
    const sql = `
      DROP TYPE priority_level;
      CREATE TYPE priority_level AS ENUM ('low', 'medium', 'high', 'critical');
      ALTER TABLE tasks
        ALTER COLUMN priority TYPE priority_level;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule] });
    // No text-cast USING -> no flag from this rule (other rules may fire for ALTER COLUMN TYPE)
    assert.strictEqual(res.findings.filter(f => f.ruleId === 'enum-recreate-table-rewrite').length, 0);
  });

  it('suggestion mentions ALTER TYPE RENAME VALUE for PG16+', () => {
    const sql = `
      DROP TYPE user_status;
      CREATE TYPE user_status AS ENUM ('active', 'inactive', 'suspended');
      ALTER TABLE users
        ALTER COLUMN status TYPE user_status USING status::text::user_status;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule], pgVersion: 16 });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].suggestion.includes('RENAME VALUE'));
  });

  it('suggestion mentions application-layer restriction for PG < 16', () => {
    const sql = `
      DROP TYPE user_status;
      CREATE TYPE user_status AS ENUM ('active', 'inactive', 'suspended');
      ALTER TABLE users
        ALTER COLUMN status TYPE user_status USING status::text::user_status;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule], pgVersion: 15 });
    assert.strictEqual(res.blockersCount, 1);
    assert.ok(res.findings[0].suggestion.includes('application'));
  });

  it('passes when ignored with directive comment', () => {
    const sql = `
      DROP TYPE user_status;
      CREATE TYPE user_status AS ENUM ('active', 'inactive');
      -- ddlforge-ignore enum-recreate-table-rewrite
      ALTER TABLE users ALTER COLUMN status TYPE user_status USING status::text::user_status;
    `;
    const res = analyzeSql(sql, { rules: [enumRecreateTableRewriteRule] });
    assert.strictEqual(res.findings.length, 0);
  });

  it('detects enum-recreate-table-rewrite in analyzeSql default rules', () => {
    const sql = `
      DROP TYPE status_type;
      CREATE TYPE status_type AS ENUM ('a', 'b');
      ALTER TABLE t ALTER COLUMN s TYPE status_type USING s::text::status_type;
    `;
    const res = analyzeSql(sql);
    assert.ok(res.findings.some(f => f.ruleId === 'enum-recreate-table-rewrite'));
  });
});

